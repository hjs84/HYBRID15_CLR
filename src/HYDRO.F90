!======================================================================!
subroutine ADVANCE_SNOW
!----------------------------------------------------------------------!
! Uses method of Merz et al. (2022).
!----------------------------------------------------------------------!
use PARS_MOD
use VARS_MOD
!----------------------------------------------------------------------!
implicit none
!----------------------------------------------------------------------!
if (TC <= (TS - DT)) then
  x = zero
else if (TC >= (TS + DT)) then
  x = one
else
  x = ((TC - (TS - DT)) / ((TS + DT) - (TS - DT))) ** b_S
end if
rain = day_s * x * pre_l
snow = day_s * pre_l - rain
!----------------------------------------------------------------------!
! Modified from Merz et al. (2022).
!----------------------------------------------------------------------!
ddf = DDF_NR + ((DDF_R - DDF_NR) / DDF_INC) * rain
ddf = min (ddf, DDF_R)
!----------------------------------------------------------------------!
if (TC >= TM) then
  melt = ((TC - TM) * ddf)
else
  melt = zero
end if
melt = min (melt, snowpack)
snowpack = snowpack + snow - melt
!----------------------------------------------------------------------!
! Convert to mm s-1
!----------------------------------------------------------------------!
melt = melt / day_s
rain = rain / day_s
snow = snow / day_s
!----------------------------------------------------------------------!
end subroutine ADVANCE_SNOW
